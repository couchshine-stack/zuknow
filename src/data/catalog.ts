export function getCategory(slug: string) {
  return [...CATEGORIES, ...SERVICES].find((c) => c.slug === slug);
}

export function getItem(slug: string) {
  return CATALOG.find((item) => item.slug === slug);
}

export function getItemById(id: string) {
  return CATALOG.find((item) => item.id === id);
}

export function itemsByCategory(slug: string) {
  return CATALOG.filter((item) => item.category === slug);
}

export function searchItems(query: string) {
  const q = query.trim().toLowerCase();
  if (!q) return CATALOG;
  if (q === "off" || q === "deal") {
    return CATALOG.filter((item) => item.mrp && item.mrp > item.price);
  }
  return CATALOG.filter((item) =>
    [item.name, item.blurb, item.unit, item.category, ...item.tags].join(" ").toLowerCase().includes(q),
  );
}

export function featuredItems() {
  return CATALOG.filter((item) => item.kind === "product").slice(0, 10);
}

export function dealItems() {
  return CATALOG.filter((item) => item.mrp && item.mrp > item.price).slice(0, 8);
}

export function serviceItems() {
  return CATALOG.filter((item) => item.kind === "service");
}
